import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { $ } from "bun";

// svelte's a11y checks read aria-query and axobject-query, through the
// tables in its `a11y/constants.js`. They're generated here, so `src/`
// keeps no dependencies, with the warnings' messages from `warnings.js`.

const root = join(import.meta.dir, "..");
const svelteDir = dirname(Bun.resolveSync("svelte/package.json", root));
const version = JSON.parse(
  readFileSync(join(svelteDir, "package.json"), "utf8"),
).version;
const A11Y = join(
  svelteDir,
  "src/compiler/phases/2-analyze/visitors/shared/a11y",
);

const constants = await import(join(A11Y, "constants.js"));
const { roles, aria } = await import(Bun.resolveSync("aria-query", svelteDir));
const { AXObjectRoles, elementAXObjects } = await import(
  Bun.resolveSync("axobject-query", svelteDir)
);

interface Schema {
  name: string;
  attributes?: { name: string; value?: string }[];
}

// A relation concept's name and attributes, the only fields the checks read.
const schema = (s: Schema): Schema =>
  s.attributes
    ? {
        name: s.name,
        attributes: s.attributes.map((a) =>
          a.value === undefined
            ? { name: a.name }
            : { name: a.name, value: a.value },
        ),
      }
    : { name: s.name };

const tables: Record<string, unknown> = {};
for (const [name, value] of Object.entries(constants)) {
  if (name.endsWith("_schemas")) {
    tables[name] = (value as Schema[]).map(schema);
  } else if (value instanceof Map) {
    tables[name] = Object.fromEntries(value);
  } else {
    tables[name] = value;
  }
}

// `roles_map.get(role)`: the props a role supports and the ones it requires.
tables.role_props = Object.fromEntries(
  roles.keys().map((role: string) => {
    const definition = roles.get(role);
    return [
      role,
      {
        props: Object.keys(definition.props),
        required: Object.keys(definition.requiredProps),
      },
    ];
  }),
);
// `aria.get(name)`: each aria-* attribute's type and, for tokens, its values.
tables.aria_properties = Object.fromEntries(
  aria.keys().map((name: string) => {
    const { type, values } = aria.get(name);
    return [name, values ? { type, values: values.map(String) } : { type }];
  }),
);
// `is_semantic_role_element`: each element schema with the roles of its AX objects.
tables.semantic_role_elements = [...elementAXObjects.entries()].map(
  ([element, objects]: [Schema, Set<string>]) => ({
    ...schema(element),
    roles: [...objects].flatMap((object) =>
      [...(AXObjectRoles.get(object) ?? [])].map(
        (r: { name: string }) => r.name,
      ),
    ),
  }),
);

const camel = (name: string) =>
  name.replace(/_(\w)/g, (_, c: string) => c.toUpperCase());
let data = `// Generated by scripts/generate-a11y.ts from svelte ${version}'s a11y constants, aria-query and axobject-query. Do not edit.\n`;
for (const [name, value] of Object.entries(tables).sort(([a], [b]) =>
  a.localeCompare(b),
)) {
  data += `\nexport const ${camel(name)} = ${JSON.stringify(value)} as const;\n`;
}
const dataFile = join(root, "src/a11y-data.ts");
writeFileSync(dataFile, data);

// The messages of the a11y warnings svelte's checks give, links included,
// as svelte words them. `warnings.js` has one more, which nothing gives.
const warnings = readFileSync(
  join(svelteDir, "src/compiler/warnings.js"),
  "utf8",
);
const checks = readFileSync(join(A11Y, "index.js"), "utf8");
const used = new Set(
  [...checks.matchAll(/\bw\.(a11y_\w+)\(/g)].map(([, code]) => code),
);
const FUNCTION =
  /\/\*\*((?:(?!\*\/)[\s\S])*)\*\/\nexport function (a11y_\w+)\(node(?:, [\w, ]+)?\) \{\n\tw\(node, '(\w+)', (`[\s\S]*?`)\);\n\}/g;
// Each parameter but `node`, typed as its JSDoc says, since a suggestion can be null.
const PARAM = /@param \{([^}]+)\} (\[)?(\w+)\]?/g;
let messages = `// Generated by scripts/generate-a11y.ts from svelte ${version}'s warnings.js. Do not edit.\n`;
const codes: string[] = [];
for (const [, doc, name, code, template] of warnings.matchAll(FUNCTION)) {
  if (name !== code) throw new Error(`${name} warns with ${code}`);
  if (!used.has(code)) continue;
  codes.push(code);
  const args = [...doc.matchAll(PARAM)]
    .filter(([, , , param]) => param !== "node")
    .map(
      ([, type, optional, param]) => `${param}${optional ? "?" : ""}: ${type}`,
    );
  const body = template.includes("${")
    ? template.replace(/\n\t\t/g, "\n    ")
    : JSON.stringify(Function(`return ${template}`)());
  messages += `\nexport function ${code}(${args.join(", ")}): string {\n  return ${body};\n}\n`;
}
const missing = [...used].filter((code) => !codes.includes(code));
if (missing.length > 0) {
  throw new Error(`not found in svelte's warnings.js: ${missing.join(", ")}`);
}
const messagesFile = join(root, "src/a11y-messages.ts");
writeFileSync(messagesFile, messages);

await $`bunx biome format --write ${dataFile} ${messagesFile}`.quiet();
console.log(
  `✓ ${Object.keys(tables).length} tables written to src/a11y-data.ts, ${codes.length} messages to src/a11y-messages.ts`,
);
