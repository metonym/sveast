import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { $ } from "bun";

const root = join(import.meta.dir, "..");
const svelte = join(root, "node_modules/svelte");
const read = (path: string) => readFileSync(join(svelte, path), "utf8");
const version = JSON.parse(read("package.json")).version;

/** The quoted strings in the `[ … ]` after `start` in `source`. */
function listAfter(source: string, start: string, file: string): string[] {
  const from = source.indexOf(start);
  const to = source.indexOf("]", from);
  if (from === -1 || to === -1) throw new Error(`no ${start} in ${file}`);
  return [...source.slice(from, to).matchAll(/'(\w+)'/g)].map((m) => m[1]);
}

const codes = listAfter(
  read("src/compiler/warnings.js"),
  "export const codes = [",
  "warnings.js",
);
const runtime = listAfter(
  read("src/constants.js"),
  "export const IGNORABLE_RUNTIME_WARNINGS =",
  "constants.js",
);
const ignore = read("src/compiler/utils/extract_svelte_ignore.js");
const from = ignore.indexOf("const replacements = {");
const to = ignore.indexOf("};", from);
if (from === -1 || to === -1) {
  throw new Error("no replacements in extract_svelte_ignore.js");
}
const replacements = [
  ...ignore.slice(from, to).matchAll(/'([\w-]+)': '(\w+)'/g),
].map((m) => [m[1], m[2]]);
if (codes.length < 50 || runtime.length === 0 || replacements.length === 0) {
  throw new Error(
    "svelte's warnings.js, constants.js or extract_svelte_ignore.js changed shape",
  );
}

const out = join(root, "src/warning-codes.ts");
writeFileSync(
  out,
  `// Generated by scripts/generate-warning-codes.ts from svelte ${version}'s warnings.js, constants.js and extract_svelte_ignore.js. Do not edit.

/** The codes a \`svelte-ignore\` comment can name: svelte's compiler warnings and the runtime ones it lets a comment silence. */
export const SVELTE_CODES: readonly string[] = ${JSON.stringify([...codes, ...runtime])};

/** svelte 4's codes that svelte 5 renamed, besides \`-\` to \`_\`. */
export const REPLACEMENTS: Readonly<Record<string, string>> = ${JSON.stringify(Object.fromEntries(replacements))};
`,
);
await $`bun fmt ${out}`.quiet();
console.log(
  `✓ ${codes.length + runtime.length} codes and ${replacements.length} replacements written to src/warning-codes.ts`,
);
